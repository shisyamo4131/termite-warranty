def wrap(text,width,size,font='JP'):
    lines=[]; current=''
    for ch in re.findall(r'[A-Za-z0-9][A-Za-z0-9/_-]*|[^\n]|\n', text):
        if ch=='\n': lines.append(current); current=''; continue
        if current and pdfmetrics.stringWidth(current+ch,font,size)>width:
            if ch in '、。，．！？：；）］｝〉》」』】':
                current+=ch
            elif current[-1] in '（［｛〈《「『【':
                lines.append(current[:-1]); current=current[-1]+ch
            else:
                lines.append(current); current=ch
        else: current+=ch
    if current: lines.append(current)
    return lines

